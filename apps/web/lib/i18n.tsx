const DICT: Record<Lang, Record<Key, string>> = { vi, en };
const STORAGE = "uno-chess:lang";

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: (key: Key, vars?: Record<string, string | number>) => string }
const I18nContext = createContext<Ctx | null>(null);

const detect = (): Lang => {
  try {
    const saved = localStorage.getItem(STORAGE);
    if (saved === "vi" || saved === "en") return saved;
  } catch {}
  return navigator.language?.toLowerCase().startsWith("vi") ? "vi" : "en";
};

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("vi"); // matches the server-rendered HTML; real value arrives after mount
  useEffect(() => setLangState(detect()), []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE, l); } catch {}
  }, []);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang,
      t: (key, vars) => {
        const s = DICT[lang][key] ?? key;
        return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : s;
      },
    }),
    [lang, setLang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT(): Ctx {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useT must be used inside <LangProvider>");
  return c;
}

/** Translates a message from the game server (English rule errors); unknown text is shown as is. */
export function gameError(t: Ctx["t"], msg: string): string {
  const key = (msg.startsWith("Expected phase") ? "err.Expected phase" : `err.${msg}`) as Key;
  return key in vi ? t(key) : msg;
}

/** Message for an error thrown by `api()` (it carries the server's stable `code`). */
export function apiError(t: Ctx["t"], e: any, fallback: Key = "api.network"): string {
  const key = `api.${e?.code}` as Key;
  return e?.code && key in vi ? t(key) : e?.message || t(fallback);
}
